CREATE DATABASE IF NOT EXISTS tax_automation CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE tax_automation;

CREATE TABLE IF NOT EXISTS categories (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  description VARCHAR(255) NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS staff (
  id INT AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(100) UNIQUE NULL,
  mobile_number VARCHAR(20) NULL,
  role VARCHAR(50) NOT NULL DEFAULT 'Staff',
  access_level ENUM('HIGH','MEDIUM','LOW') NOT NULL DEFAULT 'LOW',
  password VARCHAR(255) NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS clients (
  id INT AUTO_INCREMENT PRIMARY KEY,
  business_name VARCHAR(150) NOT NULL,
  contact_name VARCHAR(100) NOT NULL,
  mobile_number VARCHAR(20) NOT NULL UNIQUE,
  gst_details VARCHAR(20) NULL,
  pan_details VARCHAR(15) NULL,
  tan_details VARCHAR(15) NULL,
  email VARCHAR(255) NULL,
  alias_name VARCHAR(150) NULL,
  category_id INT NULL,
  assigned_staff_id INT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE SET NULL,
  FOREIGN KEY (assigned_staff_id) REFERENCES staff(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS client_categories (
  client_id INT NOT NULL,
  category_id INT NOT NULL,
  PRIMARY KEY (client_id, category_id),
  FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE CASCADE,
  FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS compliance_dates (
  id INT AUTO_INCREMENT PRIMARY KEY,
  category_id INT NOT NULL,
  description VARCHAR(255) NOT NULL,
  due_date DATE NOT NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS invoices (
  id INT AUTO_INCREMENT PRIMARY KEY,
  client_id INT NOT NULL,
  invoice_number VARCHAR(50) NOT NULL UNIQUE,
  amount DECIMAL(12,2) NOT NULL,
  service_type VARCHAR(100) NOT NULL,
  is_sent BOOLEAN NOT NULL DEFAULT FALSE,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS message_history (
  id INT AUTO_INCREMENT PRIMARY KEY,
  client_id INT NOT NULL,
  message_type VARCHAR(50) NOT NULL,
  message_content VARCHAR(500) NULL,
  sent_timestamp DATETIME DEFAULT CURRENT_TIMESTAMP,
  status ENUM('PENDING','SENT','FAILED','DELIVERED','READ') NOT NULL DEFAULT 'PENDING',
  FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS client_tasks (
  id INT AUTO_INCREMENT PRIMARY KEY,
  client_id INT NOT NULL,
  staff_id INT NULL,
  matter VARCHAR(200) NOT NULL,
  assigned_staff VARCHAR(100) NULL,
  date_assigned DATE NULL,
  due_date DATE NULL,
  next_followup_date DATE NULL,
  status ENUM('PENDING','IN_PROGRESS','WAITING_DOCUMENTS','ON_HOLD','UNDER_REVIEW','COMPLETED','CANCELLED') NOT NULL DEFAULT 'PENDING',
  remarks TEXT NULL,
  documents VARCHAR(500) NULL,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE CASCADE,
  FOREIGN KEY (staff_id) REFERENCES staff(id) ON DELETE SET NULL
);
